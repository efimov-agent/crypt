#!/bin/sh
# PreToolUse hook for Kiro CLI agents: the pending tool call arrives as JSON on stdin.
# Migration *.Designer.cs files and the model snapshot are written only by `dotnet ef`
# (a shell command), so a file-tool write to them is a hand edit. Exit code 2 blocks the
# call and its stderr is shown to the agent. Editing the Up/Down body of a migration
# (e.g. adding migrationBuilder.Sql for a data backfill) stays allowed.
if grep -Eq '"path"[[:space:]]*:[[:space:]]*"[^"]*Migrations(/|\\\\)[^"/\\]*(\.Designer\.cs|ModelSnapshot\.cs)"'; then
  echo "Blocked: migration Designer files and the model snapshot are generated by EF Core. Change the model and run 'dotnet ef migrations add <Name>' (or 'dotnet ef migrations remove' to redo the last one) instead of editing them." 1>&2
  exit 2
fi
exit 0
